const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const frontendRoot = path.resolve(__dirname, '..')
const messageSource = fs.readFileSync(path.join(frontendRoot, 'api/message.uts'), 'utf8')
const messageCenterSource = fs.readFileSync(path.join(frontendRoot, 'components/XsaMessageCenter.uvue'), 'utf8')
// 跨仓路径统一走 tests/helpers/cross-repo.cjs；后端源码不可达时显式 SKIP
// （runner 的 SKIP 协议），不静默假装通过。
const { readBackend } = require('./helpers/cross-repo.cjs')
if (readBackend('app/api/routes/social.py') == null
  || readBackend('app/api/routes/discovery.py') == null
  || readBackend('app/schemas/social.py') == null) {
  console.log('SKIP test-message-real-contract.js 后端源码不可达（设置 XSA_BACKEND_ROOT 可启用跨仓断言）')
  process.exit(0)
}
const socialRoutes = readBackend('app/api/routes/social.py')
const discoveryRoutes = readBackend('app/api/routes/discovery.py')
const socialSchemas = readBackend('app/schemas/social.py')

assert.match(messageSource, /export const MESSAGE_USE_MOCK = USE_MOCK/, '普通用户消息中心必须使用真实接口')
assert.match(messageSource, /export const CHAT_USE_MOCK = USE_MOCK/, '聊天详情必须使用真实接口')
assert.match(messageSource, /url: '\/chat\/sessions'/, '消息列表必须读取服务端会话')
assert.match(messageSource, /url: '\/chat\/sessions\/' \+ sessionId \+ '\/messages'/, '聊天记录必须使用服务端 session id')
assert.ok(messageSource.includes("'/discovery/applications/incoming'"), '收到的申请必须读取真实 discovery 接口')
assert.ok(messageSource.includes("'/discovery/applications/outgoing'"), '发出的申请必须读取真实 discovery 接口')
assert.ok(messageSource.includes("'/discovery/applications/' + applicationId"), '申请处理必须使用真实 discovery 操作接口')
assert.ok(messageSource.includes("'/chat/sessions/' + sessionId + '/read'"), '已读必须使用会话级真实接口')
assert.doesNotMatch(messageSource, /\/message\/(list|applications|read-all|application\/handle)/, '普通消息链路不能继续调用不存在的旧 message 接口')
assert.match(messageSource, /client_message_id: resolvedClientMessageId/, '发送消息必须携带稳定幂等键')
assert.doesNotMatch(messageSource, /url: '\/chat\/sessions\/' \+ userId \+ '\/messages'/, '不能把用户 ID 当作会话 ID')
assert.match(messageSource, /PARENT_BACKEND_NOT_AVAILABLE/, '父母端未接入真实消息后端时必须 fail-closed')
assert.ok(messageSource.includes("url: '/chat/messages/' + messageId"), '撤回必须调用后端真实聊天消息接口')
assert.ok(messageSource.includes("return okResponse({ messageId: messageId, revoked: true"), '后端 204 撤回成功应适配到页面响应')
const facadeRoutes = fs.readFileSync(path.join(backendRoot, 'app/api/routes/message.py'), 'utf8')
assert.match(facadeRoutes, /contact-exchanges/, '已接入的联系方式必须有服务端路由')
assert.match(facadeRoutes, /get_chat_permission/, '媒体和联系方式接口必须核验双方同意')
assert.match(messageSource, /PARENT_TEXT_ONLY/, '父母端不得交换联系方式')
assert.match(messageSource, /getChatPermission\(userId, subject\)/, '上传前必须检查聊天权限')
assert.match(messageCenterSource, /unreadTotal\.value = conversations\.value\.reduce/, '翻页后未读数必须保留前页贡献')
assert.match(messageCenterSource, /incomingPendingCount\.value = incomingApplications\.value\.filter/, '翻页后待处理数必须保留前页贡献')
assert.match(messageCenterSource, /conversationHasMore\.value && conversations\.value\.length > 0 && !allReadConfirmed\.value/, '未加载页可能未读时不得禁用全部已读')
assert.match(messageCenterSource, /unreadTotal\.value = 0\s+allReadConfirmed\.value = true/, '全部已读仅在服务端确认成功后清零')

assert.match(socialRoutes, /@router\.get\("\/chat\/sessions"/, '后端必须提供会话列表')
assert.match(socialRoutes, /@router\.get\("\/chat\/sessions\/\{session_id\}\/messages"/, '后端必须提供聊天记录')
assert.match(socialRoutes, /@router\.post\("\/chat\/sessions\/\{session_id\}\/messages"/, '后端必须提供发送消息')
assert.match(socialRoutes, /@router\.post\("\/chat\/sessions\/\{session_id\}\/read"/, '后端必须提供会话已读')
assert.match(socialRoutes, /@router\.delete\("\/chat\/messages\/\{message_id\}"/, '后端必须提供真实撤回路由')
assert.match(discoveryRoutes, /@router\.post\("\/applications\/\{application_id\}\/accept"/, '后端必须提供同意申请')
assert.match(discoveryRoutes, /@router\.post\("\/applications\/\{application_id\}\/reject"/, '后端必须提供拒绝申请')
assert.match(socialSchemas, /client_message_id: str \| None = Field\(default=None, max_length=128\)/, '后端消息模型必须限制幂等键长度')
assert.match(messageSource, /双方尚无可用聊天会话/, '未建立匹配会话时前端必须保持不可聊天')

console.log('PASS real message center/backend contract')
