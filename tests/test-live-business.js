const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { load, calls } = require('./live-demo-loader.cjs')();
const d = load('pagesSub/live/demo.uts');
const snap = () => d.demoSnapshot();
let serial = 0;
const act = (action, extra = {}) => d.demoCommand({action, command_id:'business-'+ ++serial, expected_revision:snap().revision, ...extra});
const as = id => d.demoSwitchActor(id);
d.demoReset();
assert.equal(snap().members.filter(m => m.role === 'operator').length, 1, 'independent operator');
as(1); assert.ok(!snap().allowed_actions.includes('schedule'));
assert.ok(!snap().allowed_actions.includes('cancel'));
d.demoReady(); act('start'); act('advance');
as(5); assert.throws(() => act('hand', {value:true}));
as(2); act('hand', {value:true}); act('hand', {value:false});
assert.equal(snap().members.find(m=>m.user_id===2).hand,false);
as(1); assert.ok(!snap().allowed_targets.remove_ids.includes(13));
assert.throws(()=>act('remove',{target_id:13,reason:'越权移出运营'}));
as(13); const stage=snap().members.filter(m=>m.on_stage).map(m=>m.user_id);
act('take_control',{reason:'主持断线，运营接管'});
assert.equal(snap().controller_id,13);
assert.deepEqual(snap().members.filter(m=>m.on_stage).map(m=>m.user_id),stage);
as(1); assert.throws(()=>act('pause')); as(13); act('pause');
as(2); assert.ok(!snap().allowed_actions.includes('hand'));
as(13); act('return_control',{reason:'主持恢复'}); as(1); act('resume'); act('advance');
assert.ok(!snap().members.some(m=>m.hand));
as(2); assert.throws(()=>act('hand',{value:true}));
as(4); act('leave'); as(1); act('skip_round',{reason:'主嘉宾已离场'}); act('advance');
assert.equal(snap().round_index,1);
const read = file => fs.readFileSync(path.join(__dirname,'..',file),'utf8');
assert.match(read('pagesSub/live/room.uvue'), /media_mode\s*==\s*'trtc'/);
assert.match(read('pagesSub/live/backstage.uvue'), /media_mode\s*==\s*'trtc'/);
assert.match(read('pagesSub/live/LiveStaffPanel.uvue'), /allowed_targets/);
assert.match(read('pagesSub/live/LiveRoundActions.uvue'), /allowed_actions/);
assert.equal(calls.length,0);
console.log('PASS live business: independent operator, controller, question eligibility, target scope, media guards');
