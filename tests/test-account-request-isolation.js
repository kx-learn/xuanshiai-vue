const assert = require('node:assert/strict')
const { runtime } = require('./test-parent-audit-regressions')

async function main() {
  const pending = []
  const r = runtime(new Map(), options => pending.push(options))
  r.login(101)
  const request = r.load('api/request.uts').request
  const first = request({ url: '/parent/context' })
  r.login(202)
  pending.shift().success({ statusCode: 200, data: { parent: { id: 101 } } })
  assert.equal((await first).code, 'ACCOUNT_CHANGED', 'old response exposed another account')
  r.login(101)
  const unauthorized = request({ url: '/emotion-lab/summary' })
  r.login(202)
  pending.shift().success({ statusCode: 401, data: { detail: 'expired' } })
  assert.equal((await unauthorized).code, 'ACCOUNT_CHANGED')
  assert.ok(r.config.getAccessToken(), 'old 401 cleared the new login')
  const current = request({ url: '/emotion-lab/summary' })
  pending.shift().success({ statusCode: 200, data: { owner: 202 } })
  assert.equal((await current).data.owner, 202)
  assert.equal(r.load('api/message.uts').MESSAGE_USE_MOCK, false, 'counterparty messages must use the same real backend')
  const parent = r.load('api/parent.uts')
  const context = r.load('mock/parent.uts').getMockParentContextData()
  context.dataMode = 'http'
  context.releaseGate = { productionReady: true, code: 'OK', message: 'test capability' }
  const secondPage = parent.getParentCandidates(context, 2)
  const pageRequest = pending.shift()
  assert.ok(pageRequest.url.includes('/parent/children/9201/candidates?page=2&pageSize=20'))
  pageRequest.success({ statusCode: 200, data: { items: [{ id: 303 }], page: 2, total: 21, hasMore: false } })
  const page = await secondPage
  assert.equal(page.page, 2)
  assert.equal(page.total, 21)
  assert.equal(page.hasMore, false)
  assert.equal(page.data[0].id, 303)
  const like = parent.toggleParentLike(context, 303, true)
  const likeRequest = pending.shift()
  assert.ok(likeRequest.url.endsWith('/parent/children/9201/likes/303'), 'liking must not consume a profile browse request')
  assert.equal(likeRequest.method, 'PUT')
  assert.equal(likeRequest.data.liked, true)
  likeRequest.success({ statusCode: 200, data: { success: true, userId: 303, liked: true } })
  assert.equal((await like).success, true)
  assert.equal(pending.length, 0)
  const messages = r.load('api/message.uts')
  const session = messages.getChatSessionId(303)
  const permissionRequest = pending.shift()
  assert.ok(permissionRequest.url.includes('/chat/sessions?'))
  permissionRequest.success({ statusCode: 200, data: { items: [{ id: 901, target: { user_id: 303 } }], has_more: false } })
  assert.equal((await session).data.id, 901, 'advisor must receive the server session ID, not the peer user ID')
  const blockedSession = messages.getChatSessionId(404)
  pending.shift().success({ statusCode: 200, data: { items: [], has_more: false } })
  assert.equal((await blockedSession).code, 'SESSION_NOT_FOUND')
  const parentPermission = messages.getChatPermission(303, { mode: 'parent', childId: 9201 })
  const parentPermissionRequest = pending.shift()
  assert.ok(parentPermissionRequest.url.includes('/parent/children/9201/message/chat/permission?userId=303'))
  parentPermissionRequest.success({ statusCode: 403, data: { detail: '子女授权已撤销' } })
  assert.equal((await parentPermission).success, false, 'revoked server authorization cannot fall back to ordinary-user messages')
  console.log('PASS account response isolation, stale 401 protection and shared message backend')
  console.log('PASS parent HTTP pagination and explicit private-like contract')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
